function isNativeButtonRender(render: ButtonPrimitive.Props['render']) {
  if (!render || !isValidElement(render)) {
    return true
  }

  return render.type === 'button'
}

function Button({
  className,
  variant = 'default',
  size = 'default',
  nativeButton,
  render,
  children,
  ...props
}: ButtonPrimitive.Props & VariantProps<typeof buttonVariants>) {
  const { onPointerDown, removeRipple, ripples } = useRipple()

  return (
    <ButtonPrimitive
      data-slot='button'
      className={cn(buttonVariants({ variant, size, className }))}
      nativeButton={nativeButton ?? isNativeButtonRender(render)}
      render={render}
      {...mergeProps({ onPointerDown }, props)}
    >
      <RippleContainer ripples={ripples} onRemove={removeRipple} />
      {children}
    </ButtonPrimitive>
  )
}

export { Button, buttonVariants }
